    def add_contract():
        global DB
        contractor=simpledialog.askstring("پیمانکار جدید","نام پیمانکار:",parent=root)
        if not contractor:return
        number=simpledialog.askstring("قرارداد جدید","شماره قرارداد:",parent=root)
        if not number:return
        project=simpledialog.askstring("موضوع قرارداد","موضوع پیمان:",parent=root) or ""
        import uuid
        ident="contract_"+uuid.uuid4().hex[:12]
        it={"id":ident,"contractor":contractor,"contract":number,"project":project}
        old=DB;DB=contracts/(ident+".sqlite3")
        try:
            with db() as conn:
                for k,v in [("contractor",contractor),("contract_no",number),("project",project)]:
                    conn.execute("insert or replace into settings values(?,?)",(k,v))
        finally:DB=old
        items.insert(0,it);save();state["selected"]=0;redraw()
    def edit_contract():
        if not items:return
        it=items[min(state["selected"],len(items)-1)]
        name=simpledialog.askstring("ویرایش","نام پیمانکار:",initialvalue=it.get("contractor",""),parent=root)
