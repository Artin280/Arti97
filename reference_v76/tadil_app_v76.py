def _jalali_jdn(y,m,d):
    # Arithmetic Persian calendar (2820-year cycle); exact day differences for the dates used here.
    epbase=y-(474 if y>=0 else 473)
    epyear=474+(epbase%2820)
    mdays=(m-1)*31 if m<=7 else (m-1)*30+6
    return d+mdays+((epyear*682-110)//2816)+(epyear-1)*365+(epbase//2820)*1029983

def _jalali_leap(y):
    return (_jalali_jdn(y+1,1,1)-_jalali_jdn(y,1,1))==366

