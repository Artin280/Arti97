    def _persist_settings(self, notify=False):
        """Persist settings to active SQLite and reconcile catalog without silent data loss."""
        values=self._settings_values()
        db_path=self.contract_db_path
        if not db_path.is_file():
            raise RuntimeError("بانک قرارداد انتخاب‌شده وجود ندارد: " + str(db_path))
        # Backup before writing; never overwrite an existing backup.
        backup_dir=DATA_HOME/"backup";backup_dir.mkdir(parents=True,exist_ok=True)
        backup=backup_dir/(db_path.stem+"_before_save_"+datetime.datetime.now().strftime("%Y%m%d_%H%M%S_%f")+".sqlite3")
        with sqlite3.connect(backup) as dest:self.c.backup(dest)
        # Never silently replace previously populated metadata with an all-blank form.
        existing=dict(self.c.execute("select k,v from settings"))
        identity=("contractor","contract_no","project")
        if any(existing.get(k,"").strip() for k in identity) and not any(values.get(k,"").strip() for k in identity):
            raise RuntimeError("مشخصات قرارداد در صفحه خالی است؛ برای جلوگیری از پاک شدن اطلاعات، ذخیره انجام نشد. قرارداد را دوباره انتخاب کنید.")
        self.c.executemany("insert or replace into settings(k,v) values(?,?)",values.items())
        self.c.commit()
        with sqlite3.connect(db_path) as check:
            stored=dict(check.execute("select k,v from settings"))
        if any(stored.get(k)!=v for k,v in values.items()):
            raise RuntimeError("ثبت مشخصات در بانک قرارداد تأیید نشد.")
        cat=DATA_HOME/"contracts.json"
        try:entries=json.loads(cat.read_text(encoding="utf-8")) if cat.exists() else []
        except (ValueError,OSError) as ex:raise RuntimeError("فهرست قراردادها خوانده نشد: "+str(ex))
        contract_id=db_path.stem
        found=False
        for item in entries:
            if item.get("id")==contract_id:
                item.update(contractor=values.get("contractor",""),contract=values.get("contract_no",""),project=values.get("project",""))
                found=True;break
        if not found:
            entries.append({"id":contract_id,"contractor":values.get("contractor",""),"contract":values.get("contract_no",""),"project":values.get("project","")})
        tmp=cat.with_name(cat.name+".tmp")
        tmp.write_text(json.dumps(entries,ensure_ascii=False,indent=2),encoding="utf-8")
        os.replace(tmp,cat)
        self._settings_snapshot=values.copy()
        if notify:messagebox.showinfo("ذخیره","اطلاعات قرارداد ذخیره شد و از بانک دوباره خوانده شد.",parent=self)

