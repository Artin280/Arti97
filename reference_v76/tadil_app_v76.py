        if no is None:return
        proj=simpledialog.askstring("ویرایش","موضوع پیمان:",initialvalue=it.get("project",""),parent=root)
        if proj is None:return
        it.update(contractor=name,contract=no,project=proj);save()
        path=contracts/(it["id"]+".sqlite3")
        if path.exists():
            with sqlite3.connect(path) as conn:
                for k,v in [("contractor",name),("contract_no",no),("project",proj)]:conn.execute("insert or replace into settings values(?,?)",(k,v))
